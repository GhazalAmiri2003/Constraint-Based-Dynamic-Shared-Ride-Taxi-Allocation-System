class UserSerializer(serializers.ModelSerializer):
    role = serializers.SerializerMethodField()

    class Meta:
        model = User
        fields = [
            "id",
            "username",
            "email",
            "first_name",
            "last_name",
            "role",
        ]

    def get_role(self, obj):
        if obj.is_superuser or obj.is_staff:
            return "ADMIN"

        if hasattr(obj, "profile"):
            return obj.profile.role

        return None


